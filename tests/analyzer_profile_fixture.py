def build(directory, project, label, expected=0, identities=()):
    command = ['dotnet', 'build', str(project), '--no-restore', '--nologo']
    result = subprocess.run(command, cwd=directory, capture_output=True, text=True)
    output = result.stdout + result.stderr
    (directory / (label + '.stdout.log')).write_text(result.stdout, encoding='utf-8')
    (directory / (label + '.stderr.log')).write_text(result.stderr, encoding='utf-8')
    if (expected == 0) != (result.returncode == 0) or any(identity not in output for identity in identities):
        raise AssertionError(label + ': expected native profile outcome was not established\n' + output)
    compiler_errors = set(re.findall(r'error (CS[0-9]+)', output))
    allowed = {identity for identity in identities if identity.startswith('CS')}
    if compiler_errors - allowed or 'AD0001' in output or any(identity in output and identity not in identities for identity in ('CS8784', 'CS8785')):
        raise AssertionError(label + ': compiler/analyzer setup failure cannot establish policy behavior\n' + output)
    return output


def validate_existing_profile(temporary: Path, version: str):
    directory = temporary / 'profile'
    directory.mkdir()
    project = directory / 'Profile.csproj'
    source = directory / 'Case.cs'
    config = directory / '.editorconfig'
    global_config = directory / '.globalconfig'
    (directory / 'Models.g.cs').write_text(MODELS, encoding='utf-8')
    project_text = ('<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup><TargetFramework>net10.0</TargetFramework>'
        '<FoundationSourceReadability>{selected}</FoundationSourceReadability><GenerateDocumentationFile>true</GenerateDocumentationFile>'
        '<DefineConstants>CODE_ANALYSIS</DefineConstants><FoundationFeatureIdentity>Governed</FoundationFeatureIdentity>'
        '<RestorePackagesPath>' + (temporary / 'packages').as_posix() + '</RestorePackagesPath>'
        '</PropertyGroup><ItemGroup><CompilerVisibleProperty Include="FoundationFeatureIdentity"/>'
        '<PackageReference Include="Orbyss.Foundation.Analyzers" Version="' + version + '" PrivateAssets="all"/>'
        '</ItemGroup>{extra}</Project>')
    project.write_text(project_text.format(selected='true', extra=''), encoding='utf-8')
    restore = subprocess.run(['dotnet', 'restore', str(project), '--configfile', str(temporary / 'NuGet.Config'), '--nologo'],
                             cwd=directory, capture_output=True, text=True)
    if restore.returncode:
        raise AssertionError('Existing-policy native control restore failed\n' + restore.stdout + restore.stderr)
    feature = lambda identity, body, attribute='', method_attribute='': FEATURE.format(
        identity=identity, body=body, attribute=attribute, method_attribute=method_attribute)
    cases = [
        ('layout-docs', BASIC, ['ORB1003', 'ORB1004', 'ORB1005']),
        ('shell-hosted-service', feature('Governed', 'services.AddHostedService<object>();'), ['ORB1001']),
        ('feature-identity', feature('Wrong', '_ = services;'), ['ORB1006']),
    ]
    checks = 0
    for selected in (True, False):
        prefix = 'selected' if selected else 'legacy'
        original = project_text.format(selected=str(selected).lower(), extra='')
        project.write_text(original, encoding='utf-8')
        source.write_text(GOOD, encoding='utf-8')
        config.write_text('root = true\n[*.cs]\n', encoding='utf-8')
        global_config.write_text('is_global = true\n', encoding='utf-8')
        build(directory, project, prefix + '-valid-before')
        checks += 1
        for name, bad, identities in cases:
            source.write_text(bad, encoding='utf-8')
            build(directory, project, prefix + '-' + name + '-enabled', 1, identities)
            checks += 1
            for mode in ('editorconfig', 'category', 'global', 'nowarn', 'pragma', 'combined'):
                body, text = original, bad
                editor = 'root = true\n[*.cs]\n'
                global_text = 'is_global = true\n'
                if mode in ('editorconfig', 'combined'):
                    editor += ''.join('dotnet_diagnostic.' + identity + '.severity = none\n' for identity in MANDATORY)
                if mode == 'category':
                    editor += ''.join('dotnet_analyzer_diagnostic.category-' + category + '.severity = none\n'
                                      for category in ('Lifecycle', 'Structure', 'Documentation', 'Architecture'))
                if mode == 'global':
                    global_text += 'dotnet_analyzer_diagnostic.severity = none\n'
                if mode in ('nowarn', 'combined'):
                    body = original.replace('</Project>', '<PropertyGroup><NoWarn>' + ';'.join(MANDATORY) + '</NoWarn></PropertyGroup></Project>')
                if mode in ('pragma', 'combined'):
                    text = '#pragma warning disable ' + ', '.join(MANDATORY) + '\n' + bad
                project.write_text(body, encoding='utf-8')
                source.write_text(text, encoding='utf-8')
                config.write_text(editor, encoding='utf-8')
                global_config.write_text(global_text, encoding='utf-8')
                build(directory, project, prefix + '-' + name + '-' + mode, 1 if selected else 0, identities if selected else ())
                checks += 1
            project.write_text(original, encoding='utf-8')
            config.write_text('root = true\n[*.cs]\n', encoding='utf-8')
            global_config.write_text('is_global = true\n', encoding='utf-8')
        for name, bad, identities in (
            ('suppress-message-lifecycle', feature('Governed', 'services.AddHostedService<object>();',
                method_attribute='[System.Diagnostics.CodeAnalysis.SuppressMessage("Lifecycle", "ORB1001")]\n    '), ['ORB1001']),
            ('suppress-message-identity', feature('Wrong', '_ = services;',
                attribute='[System.Diagnostics.CodeAnalysis.SuppressMessage("Architecture", "ORB1006")]\n'), ['ORB1006']),
        ):
            source.write_text(bad, encoding='utf-8')
            build(directory, project, prefix + '-' + name, 1 if selected else 0, ['CS1029', 'FoundationSourceSuppressionPolicy'] if selected else ())
            checks += 1
        checks += validate_source_suppressions(directory, project, original, source, selected)
        source.write_text(INFO, encoding='utf-8')
        config.write_text('root = true\n[*.cs]\ndotnet_diagnostic.ORB1002.severity = warning\n', encoding='utf-8')
        output = build(directory, project, prefix + '-recommendation-visible', identities=['ORB1002'])
        if 'error ORB1002' in output:
            raise AssertionError('The named-argument recommendation was strengthened into an error')
        checks += 1
        config.write_text('root = true\n[*.cs]\ndotnet_diagnostic.ORB1002.severity = none\n', encoding='utf-8')
        output = build(directory, project, prefix + '-recommendation-waivable')
        if 'ORB1002' in output:
            raise AssertionError('The named-argument recommendation lost legacy configurability')
        checks += 1
    checks += validate_generator_failures(temporary, directory, project, project_text, source)
    print(f'Existing mandatory profile controls passed ({checks} actual native builds; all five mandatory rules, legacy waivers and configurable ORB1002).')



def validate_source_suppressions(directory, project, original, source, selected):
    """Proves typed source policy facts through the actual generated native compiler error."""
    prefix = 'selected' if selected else 'legacy'
    global_source = directory / 'GlobalSuppressions.g.cs'
    constants = directory / 'Keys.g.cs'
    constants.write_text('// <auto-generated/>\nnamespace PolicyFixture { internal static class Keys { internal const string Code = "ORB1001:description"; } }', encoding='utf-8')
    feature = lambda method: FEATURE.format(identity='Governed', body='services.AddHostedService<object>();',
        attribute='', method_attribute=method + '\n    ')
    suppressed = feature('[System.Diagnostics.CodeAnalysis.SuppressMessage("Lifecycle", "ORB1001")]')
    cases = [
        ('unconditional-method', feature('[System.Diagnostics.CodeAnalysis.UnconditionalSuppressMessage("Lifecycle", "ORB1001")]'), ''),
        ('alias-constant', 'using PolicySuppression = System.Diagnostics.CodeAnalysis.SuppressMessageAttribute;\n' +
            feature('[PolicySuppression(checkId: Keys.Code, category: "Lifecycle")]'), ''),
        ('assembly-member', GOOD, '[assembly: System.Diagnostics.CodeAnalysis.SuppressMessage("Lifecycle", "ORB1001", Scope="member", Target="~M:PolicyFixture.First.Run", MessageId="value")]'),
        ('assembly-type', GOOD, '[assembly: System.Diagnostics.CodeAnalysis.UnconditionalSuppressMessage("Architecture", "ORB1006", Scope="type", Target="~T:PolicyFixture.First")]'),
        ('assembly-module', GOOD, '[assembly: System.Diagnostics.CodeAnalysis.SuppressMessage("Structure", "ORB1003", Scope="module")]'),
        ('assembly-self', suppressed, '[assembly: System.Diagnostics.CodeAnalysis.SuppressMessage("Compiler", "CS1029")]'),
        ('module-self', suppressed, '[module: System.Diagnostics.CodeAnalysis.UnconditionalSuppressMessage("Compiler", "CS1029")]'),
    ]
    mandatory = ['ORB1001', 'ORB1003', 'ORB1004', 'ORB1005', 'ORB1006', 'ORB1007', 'ORB1008', 'ORB1009', 'ORB1010']
    for identity in mandatory:
        cases.append(('complete-' + identity, GOOD.replace('internal sealed class First',
            '[System.Diagnostics.CodeAnalysis.SuppressMessage("Policy", "' + identity + ':title")]\ninternal sealed class First'), ''))
    checks = 0
    for name, text, global_text in cases:
        source.write_text(text, encoding='utf-8')
        global_source.write_text('// <auto-generated/>\n' + global_text, encoding='utf-8')
        build(directory, project, prefix + '-guard-' + name, 1 if selected else 0,
              ['CS1029', 'FoundationSourceSuppressionPolicy'] if selected else ())
        checks += 1
    # A source-level compiler-error waiver plus all common diagnostic configuration remains ineffective.
    if selected:
        (directory / '.editorconfig').write_text('root = true\n[*.cs]\ndotnet_diagnostic.CS1029.severity = none\ndotnet_analyzer_diagnostic.severity = none\n', encoding='utf-8')
        project.write_text(original.replace('</Project>', '<PropertyGroup><NoWarn>CS1029;' + ';'.join(mandatory) + '</NoWarn></PropertyGroup></Project>'), encoding='utf-8')
        source.write_text('#pragma warning disable CS1029\n' + suppressed, encoding='utf-8')
        global_source.write_text('// <auto-generated/>\n[assembly: System.Diagnostics.CodeAnalysis.SuppressMessage("Compiler", "CS1029")]', encoding='utf-8')
        build(directory, project, prefix + '-guard-combined-self', 1, ['CS1029', 'FoundationSourceSuppressionPolicy'])
        checks += 1
    project.write_text(original, encoding='utf-8')
    (directory / '.editorconfig').write_text('root = true\n[*.cs]\n', encoding='utf-8')
    global_source.write_text('', encoding='utf-8')
    for identity in ('ORB1002', 'CA1822'):
        for kind in ('SuppressMessage', 'UnconditionalSuppressMessage'):
            text = GOOD.replace('internal sealed class First', '[System.Diagnostics.CodeAnalysis.' + kind + '("Policy", "' + identity + '")]\ninternal sealed class First')
            source.write_text(text, encoding='utf-8')
            build(directory, project, prefix + '-guard-allowed-' + kind + '-' + identity)
            checks += 1
    source.write_text(GOOD.replace('internal sealed class First', '#if false\n[System.Diagnostics.CodeAnalysis.SuppressMessage("Policy", "ORB1001")]\n#endif\ninternal sealed class First'), encoding='utf-8')
    build(directory, project, prefix + '-guard-inactive-branch')
    checks += 1
    # Roslyn source suppression semantics apply independently of emitted CODE_ANALYSIS metadata.
    project.write_text(original.replace('<DefineConstants>CODE_ANALYSIS</DefineConstants>', '<DefineConstants></DefineConstants>'), encoding='utf-8')
    source.write_text(suppressed, encoding='utf-8')
    build(directory, project, prefix + '-guard-no-code-analysis', 1 if selected else 0,
          ['CS1029', 'FoundationSourceSuppressionPolicy'] if selected else ())
    checks += 1
    project.write_text(original, encoding='utf-8')
    constants.unlink()
    source.write_text(GOOD, encoding='utf-8')
    build(directory, project, prefix + '-guard-corrected')
    return checks + 1



def validate_generator_failures(temporary, directory, project, project_text, source):
    """A real faulty generator establishes the selected native compiler-warning error policy."""
    import json
    import html
    root = Path(__file__).resolve().parents[1]
    assets = json.loads((root / 'src/Orbyss.Foundation.Analyzers/obj/project.assets.json').read_text(encoding='utf-8'))
    package_roots = list(assets['packageFolders'])
    common = next(key for key in assets['libraries'] if key.startswith('Microsoft.CodeAnalysis.Common/'))
    library = assets['libraries'][common]['path']
    assembly = next(Path(folder) / library / 'lib/netstandard2.0/Microsoft.CodeAnalysis.dll'
                    for folder in package_roots if (Path(folder) / library / 'lib/netstandard2.0/Microsoft.CodeAnalysis.dll').is_file())
    faulty = temporary / 'faulty-generator'
    faulty.mkdir()
    fault_project = faulty / 'Fault.csproj'
    fault_project.write_text('<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup><TargetFramework>net10.0</TargetFramework>'
        '</PropertyGroup><ItemGroup><Reference Include="Microsoft.CodeAnalysis"><HintPath>' + html.escape(str(assembly)) +
        '</HintPath><Private>false</Private></Reference></ItemGroup></Project>', encoding='utf-8')
    (faulty / 'Faults.cs').write_text('''using System;
using Microsoft.CodeAnalysis;
[Generator] public sealed class InitializeFault : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context) => throw new InvalidOperationException("fictional initialize failure");
}
[Generator] public sealed class ExecuteFault : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterSourceOutput(context.CompilationProvider, (output, compilation) => throw new InvalidOperationException("fictional execute failure"));
    }
}
''', encoding='utf-8')
    command = ['dotnet', 'build', str(fault_project), '--configfile', str(temporary / 'NuGet.Config'), '--nologo']
    result = subprocess.run(command, cwd=faulty, capture_output=True, text=True)
    if result.returncode:
        raise AssertionError('Faulty generator fixture must compile before runtime failure controls\n' + result.stdout + result.stderr)
    plugin = faulty / 'bin/Debug/net10.0/Fault.dll'
    extra = '<ItemGroup><Analyzer Include="' + html.escape(str(plugin)) + '"/></ItemGroup>'
    source.write_text(GOOD, encoding='utf-8')
    for selected in (True, False):
        text = project_text.format(selected=str(selected).lower(), extra=extra)
        project.write_text(text, encoding='utf-8')
        build(directory, project, ('selected' if selected else 'legacy') + '-generator-failures',
              1 if selected else 0, ['CS8784', 'CS8785'])
    project.write_text(project_text.format(selected='true', extra=''), encoding='utf-8')
    build(directory, project, 'selected-generator-failure-repaired')
    return 3
