using System.Threading;
using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Operations;
using Microsoft.CodeAnalysis.Text;

namespace Orbyss.Foundation.Analyzers;

/// <summary>Rejects selected mandatory source suppressions through the native compiler error surface.</summary>
[Generator(LanguageNames.CSharp)]
public sealed class SourceSuppressionPolicyGenerator : IIncrementalGenerator
{
    /// <summary>Names this policy independently from analyzer diagnostic identities.</summary>
    public const string PolicyId = "FoundationSourceSuppressionPolicy";

    /// <summary>Uses actual mandatory descriptor owners rather than another policy inventory.</summary>
    private static readonly ImmutableHashSet<string> ProtectedIds = GetProtectedIds();

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var selected = context.AnalyzerConfigOptionsProvider.Select(IsSelected);
        var attributes = context.SyntaxProvider.CreateSyntaxProvider(IsAttribute, GetSuppression);
        var forbidden = attributes.Where(IsForbidden);
        var facts = forbidden.Collect();
        var input = selected.Combine(facts);
        context.RegisterSourceOutput(input, EmitPolicyFailures);
    }

    /// <summary>Reads the shared actual compiler-visible selection.</summary>
    private static bool IsSelected(
        Microsoft.CodeAnalysis.Diagnostics.AnalyzerConfigOptionsProvider provider,
        CancellationToken cancellationToken
    ) => SourceReadabilityAnalyzer.IsSelected(provider);

    /// <summary>Limits semantic work to native attribute syntax, including generated global metadata.</summary>
    private static bool IsAttribute(SyntaxNode node, CancellationToken cancellationToken) => node is AttributeSyntax;

    /// <summary>Admits only actual typed standard suppression attributes with constant protected identities.</summary>
    private static string? GetSuppression(GeneratorSyntaxContext context, CancellationToken cancellationToken)
    {
        var operation = context.SemanticModel.GetOperation(context.Node, cancellationToken);
        if (operation is not IAttributeOperation { Operation: IObjectCreationOperation creation })
            return null;
        var identity = creation.Constructor?.ContainingType.ToDisplayString();
        if (identity is not "System.Diagnostics.CodeAnalysis.SuppressMessageAttribute"
            and not "System.Diagnostics.CodeAnalysis.UnconditionalSuppressMessageAttribute")
        {
            return null;
        }
        foreach (var argument in creation.Arguments)
        {
            var constant = argument.Value.ConstantValue;
            if (argument.Parameter?.Name != "checkId" || !constant.HasValue || constant.Value is not string checkId)
                continue;
            var segments = checkId.Split(':');
            var diagnosticId = segments[0].Trim();
            if (!ProtectedIds.Contains(diagnosticId))
                continue;
            var position = context.Node.SyntaxTree.GetMappedLineSpan(context.Node.Span);
            var line = position.StartLinePosition.Line + 1;
            var singleLine = position.Path.Replace('\r', ' ');
            var path = singleLine.Replace('\n', ' ');
            return $"{PolicyId}: remove suppression of mandatory {diagnosticId} in {path} at line {line}; resolve the policy violation instead";
        }
        return null;
    }

    /// <summary>Keeps only typed forbidden suppression facts.</summary>
    private static bool IsForbidden(string? fact) => fact is not null;

    /// <summary>Emits intentional native compiler errors which suppression attributes cannot waive.</summary>
    private static void EmitPolicyFailures(
        SourceProductionContext context,
        (bool Selected, ImmutableArray<string?> Facts) input
    )
    {
        if (!input.Selected || input.Facts.IsEmpty)
            return;
        var lines = new List<string> { "// <auto-generated/>", "// " + PolicyId };
        foreach (var fact in input.Facts)
            lines.Add("#error " + fact);
        var text = string.Join("\n", lines);
        var source = SourceText.From(text, System.Text.Encoding.UTF8);
        context.AddSource(PolicyId + ".g.cs", source);
    }

    /// <summary>Derives the exact protected rules from existing mandatory descriptors.</summary>
    private static ImmutableHashSet<string> GetProtectedIds()
    {
        var layout = new SourceReadabilityAnalyzer();
        var descriptors = FoundationAnalyzer.SelectedDiagnostics.Concat(layout.SupportedDiagnostics);
        var ids = ImmutableHashSet.CreateBuilder<string>(StringComparer.OrdinalIgnoreCase);
        foreach (var descriptor in descriptors)
        {
            if (descriptor.DefaultSeverity == DiagnosticSeverity.Error)
                ids.Add(descriptor.Id);
        }
        return ids.ToImmutable();
    }
}
